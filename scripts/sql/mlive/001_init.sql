-- Mansel Live. New schema only. Does not touch swing, sim, daily_suggestor, or public.kite_sessions.
-- Run once against the Neon database. Safe to re-run the seed inserts (ON CONFLICT).

CREATE SCHEMA IF NOT EXISTS mlive;

CREATE TABLE IF NOT EXISTS mlive.mlive_settings (
  key         text PRIMARY KEY,
  value       jsonb NOT NULL,
  updated_at  timestamptz NOT NULL DEFAULT now(),
  updated_by  text
);

CREATE TABLE IF NOT EXISTS mlive.mlive_settings_history (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  key         text NOT NULL,
  old_value   jsonb,
  new_value   jsonb,
  changed_at  timestamptz NOT NULL DEFAULT now(),
  changed_by  text
);

CREATE TABLE IF NOT EXISTS mlive.mlive_fund_ledger (
  id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ts            timestamptz NOT NULL DEFAULT now(),
  kind          text NOT NULL CHECK (kind IN ('deposit', 'withdrawal', 'realised_pnl', 'charges')),
  dry_run       boolean NOT NULL DEFAULT false,
  amount        numeric(14,2) NOT NULL,
  ref_order_id  bigint,
  note          text
);

CREATE TABLE IF NOT EXISTS mlive.mlive_state (
  id            integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  status        text NOT NULL CHECK (status IN ('active', 'paused_by_user', 'paused_by_breaker', 'halted_today')),
  mode          text NOT NULL CHECK (mode IN ('approve', 'auto', 'paused')),
  peak_value    numeric(14,2) NOT NULL,
  peak_date     date,
  last_eod_date date,
  last_run_id   bigint,
  halt_reason   text,
  updated_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS mlive.mlive_kite_sessions (
  user_id           text PRIMARY KEY,
  access_token_enc  text NOT NULL,
  token_date        date NOT NULL,
  connected_at      timestamptz NOT NULL DEFAULT now(),
  kite_user_id      text
);

CREATE TABLE IF NOT EXISTS mlive.mlive_instruments (
  symbol      text PRIMARY KEY,
  isin        text,
  name        text,
  sector      text,
  is_etf      boolean NOT NULL DEFAULT false,
  excluded    boolean NOT NULL DEFAULT false,
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS mlive.mlive_runs (
  id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  kind         text NOT NULL CHECK (kind IN (
                 'preflight', 'sells', 'refresh', 'buys', 'approvals',
                 'sync', 'cancel', 'eod', 'eod-final', 'eod-stops', 'import-ideas', 'remind', 'reset-dry'
               )),
  started_at   timestamptz NOT NULL DEFAULT now(),
  finished_at  timestamptz,
  status       text NOT NULL DEFAULT 'running',
  summary      jsonb
);

CREATE TABLE IF NOT EXISTS mlive.mlive_ideas (
  id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  scan_date     date NOT NULL,
  valid_for     date NOT NULL,
  symbol        text NOT NULL,
  strategy      text NOT NULL CHECK (strategy IN ('rs', 'ema')),
  score         numeric(14,6) NOT NULL,
  signal_close  numeric(14,2) NOT NULL,
  initial_stop  numeric(14,2),
  sector        text,
  raw           jsonb,
  UNIQUE (scan_date, symbol, strategy)
);

CREATE TABLE IF NOT EXISTS mlive.mlive_decisions (
  id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  run_id       bigint REFERENCES mlive.mlive_runs (id),
  trade_date   date NOT NULL,
  idea_id      bigint REFERENCES mlive.mlive_ideas (id),
  position_id  bigint,
  side         text NOT NULL CHECK (side IN ('BUY', 'SELL')),
  symbol       text NOT NULL,
  outcome      text NOT NULL CHECK (outcome IN ('proposed', 'approved', 'skipped', 'sent', 'expired')),
  reason_code  text,
  reason_text  text,
  sizing       jsonb,
  rank         integer,
  dry_run      boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS mlive.mlive_approvals (
  id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  decision_id  bigint NOT NULL REFERENCES mlive.mlive_decisions (id),
  action       text NOT NULL CHECK (action IN ('approve', 'skip')),
  by_user      text NOT NULL,
  ts           timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS mlive.mlive_orders (
  id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  decision_id    bigint REFERENCES mlive.mlive_decisions (id),
  tag            text UNIQUE,
  kind           text NOT NULL DEFAULT 'order',
  kite_order_id  text,
  side           text NOT NULL CHECK (side IN ('BUY', 'SELL')),
  symbol         text NOT NULL,
  qty            integer NOT NULL CHECK (qty > 0),
  limit_price    numeric(14,2) NOT NULL,
  status         text NOT NULL,
  filled_qty     integer NOT NULL DEFAULT 0,
  avg_price      numeric(14,2),
  placed_at      timestamptz,
  updated_at     timestamptz NOT NULL DEFAULT now(),
  reject_reason  text,
  dry_run        boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS mlive.mlive_fills (
  id             bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  order_id       bigint NOT NULL REFERENCES mlive.mlive_orders (id),
  kite_trade_id  text NOT NULL UNIQUE,
  qty            integer NOT NULL,
  price          numeric(14,2) NOT NULL,
  ts             timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS mlive.mlive_positions (
  id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  symbol          text NOT NULL,
  strategy        text CHECK (strategy IN ('rs', 'ema')),
  qty             integer NOT NULL,
  avg_price       numeric(14,2) NOT NULL,
  opened_at       timestamptz NOT NULL DEFAULT now(),
  closed_at       timestamptz,
  trend_stop      numeric(14,2),
  high_52w_flag   boolean NOT NULL DEFAULT false,
  frozen          boolean NOT NULL DEFAULT false,
  realised_pnl    numeric(14,2) NOT NULL DEFAULT 0,
  charges         numeric(14,2) NOT NULL DEFAULT 0,
  dry_run         boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS mlive.mlive_gtts (
  id                bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  position_id       bigint NOT NULL REFERENCES mlive.mlive_positions (id),
  kite_trigger_id   text,
  trigger_price     numeric(14,2) NOT NULL,
  limit_price       numeric(14,2) NOT NULL,
  qty               integer NOT NULL,
  status            text NOT NULL,
  created_at        timestamptz NOT NULL DEFAULT now(),
  history           jsonb NOT NULL DEFAULT '[]'::jsonb,
  dry_run           boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS mlive.mlive_equity_daily (
  trade_date        date PRIMARY KEY,
  cash              numeric(14,2) NOT NULL,
  positions_value   numeric(14,2) NOT NULL,
  system_value      numeric(14,2) NOT NULL,
  peak              numeric(14,2) NOT NULL,
  drawdown_pct      numeric(8,4) NOT NULL
);

CREATE TABLE IF NOT EXISTS mlive.mlive_daily_reports (
  trade_date         date PRIMARY KEY,
  decision_summary   jsonb,
  text               text,
  created_at         timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS mlive.mlive_reconciliations (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  run_id      bigint REFERENCES mlive.mlive_runs (id),
  symbol      text NOT NULL,
  system_qty  integer NOT NULL,
  kite_qty    integer NOT NULL,
  result      text NOT NULL CHECK (result IN ('ok', 'missing', 'extra_ignored'))
);

CREATE TABLE IF NOT EXISTS mlive.mlive_alerts (
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ts         timestamptz NOT NULL DEFAULT now(),
  level      text NOT NULL CHECK (level IN ('needs_you', 'problem', 'done')),
  code       text NOT NULL,
  message    text NOT NULL,
  symbol     text,
  push_sent  boolean NOT NULL DEFAULT false,
  seen_at    timestamptz
);

CREATE TABLE IF NOT EXISTS mlive.mlive_audit_log (
  id       bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ts       timestamptz NOT NULL DEFAULT now(),
  actor    text NOT NULL CHECK (actor IN ('engine', 'user', 'kite', 'system')),
  action   text NOT NULL,
  symbol   text,
  before   jsonb,
  after    jsonb,
  reason   text,
  run_id   bigint
);

CREATE TABLE IF NOT EXISTS mlive.mlive_holidays (
  trade_date  date PRIMARY KEY,
  name        text NOT NULL
);

CREATE TABLE IF NOT EXISTS mlive.mlive_backtests (
  id       bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  run_at   timestamptz NOT NULL DEFAULT now(),
  params   jsonb NOT NULL,
  metrics  jsonb NOT NULL,
  chosen   boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS mlive_ideas_valid_idx ON mlive.mlive_ideas (valid_for, strategy);
CREATE INDEX IF NOT EXISTS mlive_decisions_day_idx ON mlive.mlive_decisions (trade_date, outcome);
CREATE UNIQUE INDEX IF NOT EXISTS mlive_decisions_buy_idea_day
  ON mlive.mlive_decisions (trade_date, side, idea_id) WHERE idea_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS mlive_decisions_sell_position_day
  ON mlive.mlive_decisions (trade_date, side, position_id) WHERE position_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS mlive_orders_decision_unique ON mlive.mlive_orders (decision_id);
CREATE INDEX IF NOT EXISTS mlive_positions_open_idx ON mlive.mlive_positions (symbol) WHERE closed_at IS NULL;
CREATE INDEX IF NOT EXISTS mlive_alerts_open_idx ON mlive.mlive_alerts (seen_at, ts DESC);
CREATE INDEX IF NOT EXISTS mlive_audit_ts_idx ON mlive.mlive_audit_log (ts DESC);

-- Append-only even for the table owner. REVOKE alone does not stop the owner on Neon.
CREATE OR REPLACE FUNCTION mlive.reject_audit_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'mlive_audit_log is append-only';
END;
$$;

DROP TRIGGER IF EXISTS mlive_audit_no_update ON mlive.mlive_audit_log;
CREATE TRIGGER mlive_audit_no_update
  BEFORE UPDATE OR DELETE ON mlive.mlive_audit_log
  FOR EACH ROW EXECUTE FUNCTION mlive.reject_audit_mutation();

REVOKE UPDATE, DELETE ON mlive.mlive_audit_log FROM PUBLIC;

